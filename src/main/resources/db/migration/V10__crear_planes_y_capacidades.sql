CREATE TABLE planes (
                        id UUID PRIMARY KEY,
                        codigo VARCHAR(30) NOT NULL UNIQUE,
                        nombre VARCHAR(100) NOT NULL,
                        descripcion VARCHAR(500),
                        activo BOOLEAN NOT NULL DEFAULT TRUE,
                        fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE plan_capacidades (
                                  plan_id UUID NOT NULL,
                                  capacidad VARCHAR(60) NOT NULL,

                                  CONSTRAINT fk_plan_capacidades_plan
                                      FOREIGN KEY (plan_id)
                                          REFERENCES planes(id)
                                          ON DELETE CASCADE,

                                  CONSTRAINT uk_plan_capacidad
                                      UNIQUE (plan_id, capacidad)
);

CREATE TABLE plan_limites (
                              plan_id UUID NOT NULL,
                              tipo_limite VARCHAR(60) NOT NULL,
                              valor INTEGER NOT NULL,

                              CONSTRAINT fk_plan_limites_plan
                                  FOREIGN KEY (plan_id)
                                      REFERENCES planes(id)
                                      ON DELETE CASCADE,

                              CONSTRAINT uk_plan_limite
                                  UNIQUE (plan_id, tipo_limite)
);

ALTER TABLE empresas
    ADD COLUMN plan_id UUID;

ALTER TABLE empresas
    ADD CONSTRAINT fk_empresas_plan
        FOREIGN KEY (plan_id)
            REFERENCES planes(id);

